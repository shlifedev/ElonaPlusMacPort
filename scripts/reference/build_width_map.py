#!/usr/bin/env python3
"""Convert WidthMapReference.cs output to sorted CP932 lookup tables."""
import argparse
from pathlib import Path

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('reference', type=Path)
p.add_argument('output', type=Path)
a = p.parse_args()
maps = {'400000': {}, '800000': {}}
for row in a.reference.read_text().splitlines():
    flag, source, target = row.split()
    key = 0
    for unit in source.split('+'):
        key = (key << 16) | int(unit, 16)
    assert key not in maps[flag] and len(target) <= 8
    maps[flag][key] = int(target, 16)
common = {k: v for k, v in maps['400000'].items() if maps['800000'].get(k) == v}
with a.output.open('w', newline='\n') as f:
    f.write('// Generated by scripts/reference/build_width_map.py from the Japanese Win32 LCMapStringA results.\n')
    for name, table in [('width_common', common), ('width_half', maps['400000']), ('width_full', maps['800000'])]:
        f.write('static constexpr WidthEntry ' + name + '[] = {\n')
        entries = [f'{{0x{k:x},0x{v:x}}}' for k, v in sorted(table.items()) if table is common or k not in common]
        for i in range(0, len(entries), 4):
            f.write('    ' + ', '.join(entries[i:i+4]) + ',\n')
        f.write('};\n')
